def by_slug(slug: str | None) -> dict | None:
    """Return attack metadata for a slug, or ``None`` when it is unavailable."""
    return next((attack for attack in (*ATTACKS, *FULL_ONLY_ATTACKS) if attack["slug"] == slug), None)


def by_tier(full: bool = False) -> list[tuple[int, dict, list[dict]]]:
    """Return the attack groups for the benchmark form.

    The course page shows the baseline group and the FYP's tier 2; ``full=True`` (the unlinked
    /full-benchmarks/new page) shows every FYP attack grouped by tier, as the FYP app does.
    """
    built_in = [attack for attack in ATTACKS if attack.get("dataset") != "custom"]
    if not full:
        # The course page also offers the FYP's tier-2 attacks (user request, 4 Oct 2026).
        return [(1, TIER_META[1], built_in),
                (2, FULL_TIER_META[2], [attack for attack in FULL_ONLY_ATTACKS if attack.get("tier") == 2])]
    buckets: dict[int, list[dict]] = {tier: [] for tier in FULL_TIER_META}
    for attack in (*built_in, *FULL_ONLY_ATTACKS):
        buckets[attack.get("tier") if attack.get("tier") in buckets else 2].append(attack)
    return [(tier, FULL_TIER_META[tier], buckets[tier]) for tier in FULL_TIER_META if buckets[tier]]
