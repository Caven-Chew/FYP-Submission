"""Where failure captures live on disk, how to address them safely, and when
they get deleted.

A UI target that fails to produce a reply writes two files — a full-page PNG
and the gzipped page HTML — so a failure can be diagnosed (and put in a report)
after the fact, instead of only through a vision model's prose summary that may
be wrong, skipped, or unconfigured.

Three rules keep this from turning into an ever-growing pile of megabytes:

  1. Per-run cap (``UI_CAPTURE_BUDGET``). A target showing a login wall fails
     identically on every prompt; the first N captures tell you everything the
     hundredth would.
  2. Retention by run (``UI_CAPTURE_KEEP_RUNS``). Only the most recent N
     benchmarks keep captures. Pruned on startup and at the start of every run.
  3. Cascade on delete. Deleting a benchmark deletes its capture folder —
     SQLAlchemy's cascade handles rows, nothing but this handles disk.

Paths are stored relative (``<benchmark_id>/<ref>.png``) and resolved against
ROOT at read time, never absolute — the same portability lesson `sessions.py`
documents at length, since this project moves between Windows and macOS.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from .config import ROOT
from .settings import UI_CAPTURE_KEEP_RUNS

ARTIFACTS_DIR = ROOT / "instance" / "artifacts"

# A capture ref is generated by us, never supplied by a user — but it arrives
# back through a URL, so it is validated as strictly as if it were hostile.
# Alphanumerics, dash and underscore only: no dots, no slashes, so ".." and
# absolute paths cannot be expressed at all.
_REF_RE = re.compile(r"^[A-Za-z0-9_-]{1,80}$")

_SUFFIX = {"png": ".png", "html": ".html.gz"}


def benchmark_dir(benchmark_id: int) -> Path:
    """Capture folder for one benchmark. int() coercion is the traversal guard."""
    return ARTIFACTS_DIR / str(int(benchmark_id))


def artifact_file(benchmark_id: int, ref: str, kind: str) -> Path | None:
    """Resolve (benchmark, ref, kind) to a file on disk, or None if invalid/absent.

    Returns None rather than raising for anything malformed, so a view can turn
    the whole class of bad input into one 404 without branching.
    """
    if kind not in _SUFFIX or not _REF_RE.match(ref or ""):
        return None
    path = benchmark_dir(benchmark_id) / f"{ref}{_SUFFIX[kind]}"
    return path if path.is_file() else None


def has_artifacts(benchmark_id: int, ref: str | None) -> bool:
    """True when at least one of the two files for `ref` survives on disk.

    The template asks this before rendering links, because retention may have
    pruned the files out from under a `capture_ref` still recorded on the row.
    """
    if not ref:
        return False
    return any(artifact_file(benchmark_id, ref, k) for k in _SUFFIX)


def delete_benchmark_artifacts(benchmark_id: int) -> None:
    """Remove one benchmark's capture folder. Safe to call when it never had one."""
    shutil.rmtree(benchmark_dir(benchmark_id), ignore_errors=True)


def prune(keep_runs: int = UI_CAPTURE_KEEP_RUNS) -> int:
    """Delete capture folders for orphaned and older benchmarks. Returns the count.

    Orphans (folder with no surviving Benchmark row) always go — they are the
    residue of a delete that happened while the files were in use, or of a
    dropped database. Beyond that, the newest `keep_runs` benchmarks keep their
    captures and everything older is removed.

    Called on startup and at the start of every run, so disk use stays bounded
    without a scheduled job. Never raises: losing a debugging artefact must not
    take down a benchmark, so failures here are swallowed deliberately.
    """
    if not ARTIFACTS_DIR.is_dir():
        return 0
    try:
        from .models import Benchmark

        on_disk: dict[int, Path] = {}
        for child in ARTIFACTS_DIR.iterdir():
            if child.is_dir() and child.name.isdigit():
                on_disk[int(child.name)] = child

        if not on_disk:
            return 0

        live = {b.id for b in Benchmark.query.with_entities(Benchmark.id).all()}
        keep = sorted(bid for bid in on_disk if bid in live)[-keep_runs:] if keep_runs > 0 else []

        removed = 0
        for bid, path in on_disk.items():
            if bid in keep:
                continue
            shutil.rmtree(path, ignore_errors=True)
            removed += 1
        return removed
    except Exception:  # noqa: BLE001 — housekeeping must never break a run
        return 0
